def norm(art):
    rows = [r for r in art.strip('\n').split('\n')]
    for r in rows:
        assert len(r) <= 16, (art[:40], r, len(r))
    rows = [r.ljust(16, '.') for r in rows]
    assert len(rows) <= 16, (art[:40], len(rows))
    pad = 16 - len(rows)
    top = pad // 2
    return ['.' * 16] * top + rows + ['.' * 16] * (pad - top)


