def medal(digit):
    d = {
        '1': [".K.", "KK.", ".K.", ".K.", "KKK"],
        '2': ["KK.", "..K", ".K.", "K..", "KKK"],
        '3': ["KK.", "..K", ".K.", "..K", "KK."],
    }[digit]
    rows = [
        "...KK......KK...",
        "..KDDK....KDDK..",
        "...KDDK..KDDK...",
        "....KDDKKDDK....",
        ".....KDDDDK.....",
        ".....KKKKKK.....",
        "....KLLLLLLK....",
        "...KLMMMMMMLK...",
    ]
    for r in d:
        rows.append("...KLM" + r.replace('.', 'M') + "MMLK...")
    rows += ["...KLMMMMMMLK...", "....KLLLLLLK....", ".....KKKKKK....."]
    return "\n".join(rows)

